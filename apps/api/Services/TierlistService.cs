using api.Common;
using api.Models;
using Supabase.Postgrest;
using Supabase.Postgrest.Exceptions;
using Supabase.Postgrest.Interfaces;
using Supabase.Postgrest.Responses;

namespace api.Services;

/// <summary>
/// Saves and reads the tierlists users create in the "tierlists" table, with their restaurants from the
/// "tierlist_restaurant" table.
/// </summary>
/// <param name="supabase">Client of the Supabase database.</param>
/// <param name="restaurantService">Checks that a restaurant added to a tierlist exists.</param>
public class TierlistService(Supabase.Client supabase, IRestaurantService restaurantService) : ITierlistService
{
    /// <summary>
    /// Error returned for an id that matches no tierlist.
    /// </summary>
    public static Error NotFound { get; } = new(ErrorType.NotFound, "Tierlist not found.");

    /// <summary>
    /// Error returned when a user tries to change a tierlist of another user.
    /// </summary>
    public static Error NotOwner { get; } = new(ErrorType.Forbidden, "Only the owner of a tierlist can change it.");

    /// <summary>
    /// Error returned when a restaurant is added to a tierlist that already contains it.
    /// </summary>
    public static Error RestaurantAlreadyAdded { get; } = new(ErrorType.Conflict, "This restaurant is already in the tierlist.");

    /// <summary>
    /// Error returned when the owner adds a restaurant they have not rated: the tierlist ranks by the owner's ratings.
    /// </summary>
    public static Error RestaurantNotRated { get; } = new(ErrorType.Validation, "Rate the restaurant before adding it to a tierlist.");

    /// <summary>
    /// Error returned when the restaurant to remove is not in the tierlist.
    /// </summary>
    public static Error RestaurantNotInTierlist { get; } = new(ErrorType.NotFound, "This restaurant is not in the tierlist.");

    /// <summary>
    /// Client of the Supabase database.
    /// </summary>
    private readonly Supabase.Client _supabase = supabase ?? throw new ArgumentNullException(nameof(supabase));

    /// <summary>
    /// Checks that a restaurant added to a tierlist exists.
    /// </summary>
    private readonly IRestaurantService _restaurantService = restaurantService ?? throw new ArgumentNullException(nameof(restaurantService));

    /// <inheritdoc />
    public async Task<Result<TierlistResponse>> CreateAsync(string userId, CreateTierlistRequest request, CancellationToken cancellationToken)
    {
        ModeledResponse<Tierlist> inserted = await _supabase.From<Tierlist>()
            .Insert(request.ToTierlist(userId), cancellationToken: cancellationToken);

        // The inserted row is returned with the id and dates generated by the database
        Tierlist? tierlist = inserted.Models.FirstOrDefault();
        return tierlist is null
            ? Result<TierlistResponse>.Failure(new Error(ErrorType.Unavailable, "The tierlist could not be created."))
            : Result<TierlistResponse>.Success(TierlistResponse.From(tierlist, []));
    }

    /// <inheritdoc />
    public async Task<Result<IReadOnlyList<TierlistResponse>>> GetByUserAsync(string userId, CancellationToken cancellationToken)
    {
        if (!UserIds.IsValid(userId))
            return Result<IReadOnlyList<TierlistResponse>>.Failure(UserIds.NotFound);

        ModeledResponse<Tierlist> response = await _supabase.From<Tierlist>()
            .Where(t => t.UserId == userId)
            .Order("created_at", Constants.Ordering.Descending)
            .Get(cancellationToken);
        return Result<IReadOnlyList<TierlistResponse>>.Success(await WithRestaurantsAsync(response.Models, cancellationToken));
    }

    /// <inheritdoc />
    public async Task<Result<TierlistResponse>> GetByIdAsync(long id, CancellationToken cancellationToken)
    {
        Tierlist? tierlist = await FindAsync(id, cancellationToken);
        if (tierlist is null)
            return Result<TierlistResponse>.Failure(NotFound);

        IReadOnlyList<TierlistResponse> withRestaurants = await WithRestaurantsAsync([tierlist], cancellationToken);
        return Result<TierlistResponse>.Success(withRestaurants[0]);
    }

    /// <inheritdoc />
    public async Task<Result<TierlistResponse>> SetPinnedAsync(long id, string userId, bool pinned, CancellationToken cancellationToken)
    {
        Tierlist? tierlist = await FindAsync(id, cancellationToken);
        if (tierlist is null)
            return Result<TierlistResponse>.Failure(NotFound);
        if (!tierlist.IsOwnedBy(userId))
            return Result<TierlistResponse>.Failure(NotOwner);

        tierlist.Pinned = pinned;
        await SetUpdatedAtAsync(tierlist, DateTime.UtcNow, cancellationToken);

        IReadOnlyList<TierlistResponse> withRestaurants = await WithRestaurantsAsync([tierlist], cancellationToken);
        return Result<TierlistResponse>.Success(withRestaurants[0]);
    }

    /// <inheritdoc />
    public async Task<Result<TierlistResponse>> AddRestaurantAsync(long id, string userId, string restaurantId, CancellationToken cancellationToken)
    {
        Tierlist? tierlist = await FindAsync(id, cancellationToken);
        if (tierlist is null)
            return Result<TierlistResponse>.Failure(NotFound);
        if (!tierlist.IsOwnedBy(userId))
            return Result<TierlistResponse>.Failure(NotOwner);

        Result<Restaurant> restaurant = await _restaurantService.GetByIdAsync(restaurantId, cancellationToken);
        if (!restaurant.IsSuccess)
            return Result<TierlistResponse>.Failure(restaurant.Error!);

        string restaurantKey = restaurant.Value!.Id;
        IReadOnlyList<TierlistRestaurant> entries = await GetEntriesAsync(id, cancellationToken);
        if (entries.Any(e => e.RestaurantId == restaurantKey))
            return Result<TierlistResponse>.Failure(RestaurantAlreadyAdded);

        ModeledResponse<Rating> ownerRating = await RatingService.ActiveRatingsQuery(_supabase.From<Rating>(), restaurantKey, userId)
            .Limit(1)
            .Get(cancellationToken);
        if (ownerRating.Models.Count == 0)
            return Result<TierlistResponse>.Failure(RestaurantNotRated);

        DateTime now = DateTime.UtcNow;
        TierlistRestaurant entry = new() { TierlistId = id, RestaurantId = restaurantKey, AddedAt = now };
        try
        {
            await _supabase.From<TierlistRestaurant>().Insert(entry, cancellationToken: cancellationToken);
        }
        catch (PostgrestException ex) when (PostgrestErrors.IsUniqueViolation(ex))
        {
            // Added by another request since the entries were read
            return Result<TierlistResponse>.Failure(RestaurantAlreadyAdded);
        }

        await SetUpdatedAtAsync(tierlist, now, cancellationToken);
        return Result<TierlistResponse>.Success(TierlistResponse.From(tierlist, [.. entries, entry]));
    }

    /// <inheritdoc />
    public async Task<Result<TierlistResponse>> RemoveRestaurantAsync(long id, string userId, string restaurantId, CancellationToken cancellationToken)
    {
        Tierlist? tierlist = await FindAsync(id, cancellationToken);
        if (tierlist is null)
            return Result<TierlistResponse>.Failure(NotFound);
        if (!tierlist.IsOwnedBy(userId))
            return Result<TierlistResponse>.Failure(NotOwner);

        // An unknown restaurant, or an id that is not a uuid, is never in the tierlist: no query is sent with it
        IReadOnlyList<TierlistRestaurant> entries = await GetEntriesAsync(id, cancellationToken);
        if (entries.All(e => e.RestaurantId != restaurantId))
            return Result<TierlistResponse>.Failure(RestaurantNotInTierlist);

        await EntryQuery(_supabase.From<TierlistRestaurant>(), id, restaurantId).Delete(cancellationToken: cancellationToken);

        await SetUpdatedAtAsync(tierlist, DateTime.UtcNow, cancellationToken);
        return Result<TierlistResponse>.Success(TierlistResponse.From(tierlist, entries.Where(e => e.RestaurantId != restaurantId)));
    }

    /// <summary>
    /// Query of the row of <paramref name="restaurantId"/> in the tierlist <paramref name="tierlistId"/>. Both keys are
    /// filtered, each in its own Where, so a delete sent with it never removes other rows.
    /// </summary>
    /// <param name="entries">Query on the "tierlist_restaurant" table to filter.</param>
    /// <param name="tierlistId">Database id of the tierlist.</param>
    /// <param name="restaurantId">Database id of the restaurant.</param>
    /// <returns>The filtered query, ready to send.</returns>
    public static IPostgrestTable<TierlistRestaurant> EntryQuery(IPostgrestTable<TierlistRestaurant> entries, long tierlistId, string restaurantId)
        => entries
            .Where(e => e.TierlistId == tierlistId)
            .Where(e => e.RestaurantId == restaurantId);

    /// <inheritdoc />
    public async Task RemoveRestaurantFromAllAsync(string userId, string restaurantId, CancellationToken cancellationToken)
    {
        ModeledResponse<Tierlist> tierlists = await _supabase.From<Tierlist>()
            .Where(t => t.UserId == userId)
            .Get(cancellationToken);
        if (tierlists.Models.Count == 0)
            return;

        List<long> tierlistIds = tierlists.Models.Select(t => t.Id).ToList();
        ModeledResponse<TierlistRestaurant> entries = await EntriesQuery(_supabase.From<TierlistRestaurant>(), tierlistIds, restaurantId).Get(cancellationToken);
        if (entries.Models.Count == 0)
            return;

        // Only the tierlists holding the restaurant change: their update date too
        HashSet<long> changedIds = entries.Models.Select(e => e.TierlistId).ToHashSet();
        await EntriesQuery(_supabase.From<TierlistRestaurant>(), changedIds.ToList(), restaurantId).Delete(cancellationToken: cancellationToken);
        DateTime now = DateTime.UtcNow;
        foreach (Tierlist tierlist in tierlists.Models.Where(t => changedIds.Contains(t.Id)))
            await SetUpdatedAtAsync(tierlist, now, cancellationToken);
    }

    /// <summary>
    /// Query of the rows of <paramref name="restaurantId"/> in any of the tierlists <paramref name="tierlistIds"/>. Both
    /// keys are filtered, so a delete sent with it never removes other restaurants nor touches other tierlists.
    /// </summary>
    /// <param name="entries">Query on the "tierlist_restaurant" table to filter.</param>
    /// <param name="tierlistIds">Database ids of the tierlists (not empty: PostgREST refuses an empty list).</param>
    /// <param name="restaurantId">Database id of the restaurant.</param>
    /// <returns>The filtered query, ready to send.</returns>
    public static IPostgrestTable<TierlistRestaurant> EntriesQuery(IPostgrestTable<TierlistRestaurant> entries, IReadOnlyList<long> tierlistIds, string restaurantId)
        => entries
            .Filter("id_tierlist", Constants.Operator.In, tierlistIds.Cast<object>().ToList())
            .Where(e => e.RestaurantId == restaurantId);

    /// <summary>
    /// Reads the tierlist <paramref name="id"/>, without its restaurants; null when it does not exist.
    /// </summary>
    private async Task<Tierlist?> FindAsync(long id, CancellationToken cancellationToken)
    {
        ModeledResponse<Tierlist> response = await _supabase.From<Tierlist>()
            .Where(t => t.Id == id)
            .Limit(1)
            .Get(cancellationToken);
        return response.Models.FirstOrDefault();
    }

    /// <summary>
    /// Reads the restaurant rows of the tierlist <paramref name="id"/>.
    /// </summary>
    private async Task<IReadOnlyList<TierlistRestaurant>> GetEntriesAsync(long id, CancellationToken cancellationToken)
    {
        ModeledResponse<TierlistRestaurant> response = await _supabase.From<TierlistRestaurant>()
            .Where(r => r.TierlistId == id)
            .Get(cancellationToken);
        return response.Models;
    }

    /// <summary>
    /// Saves <paramref name="tierlist"/> with <paramref name="updatedAt"/> as its last change: its new pin, or the date
    /// once a restaurant was added or removed. PostgREST runs one transaction per request: if this second request fails
    /// after an addition or a removal, the request answers an error but the restaurant stays added (or removed), with a
    /// stale date.
    /// </summary>
    private async Task SetUpdatedAtAsync(Tierlist tierlist, DateTime updatedAt, CancellationToken cancellationToken)
    {
        // Update on the primary key of the row just read; the creation date is never sent
        tierlist.UpdatedAt = updatedAt;
        await _supabase.From<Tierlist>().Update(tierlist, cancellationToken: cancellationToken);
    }

    /// <summary>
    /// Loads the restaurants of <paramref name="tierlists"/> in one query, and maps each tierlist with its restaurants.
    /// </summary>
    private async Task<IReadOnlyList<TierlistResponse>> WithRestaurantsAsync(IReadOnlyList<Tierlist> tierlists, CancellationToken cancellationToken)
    {
        if (tierlists.Count == 0)
            return [];

        List<object> tierlistIds = tierlists.Select(t => (object)t.Id).ToList();
        ModeledResponse<TierlistRestaurant> restaurants = await _supabase.From<TierlistRestaurant>()
            .Filter("id_tierlist", Constants.Operator.In, tierlistIds)
            .Get(cancellationToken);
        ILookup<long, TierlistRestaurant> restaurantsByTierlist = restaurants.Models.ToLookup(r => r.TierlistId);

        return tierlists.Select(t => TierlistResponse.From(t, restaurantsByTierlist[t.Id])).ToList();
    }
}
